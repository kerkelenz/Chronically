export function SymptomIcon({ symptom, size = 20, color = "white" }) {
  if (!symptom) return null;
  const Icon = SYMPTOM_REGISTRY[symptomIconName(symptom)] || Symptom;
  return <Icon color={color} width={size} height={size} />;
}

export function MedicationTypeIcon({ type, size = 20, color = "white" }) {
  const Icon = MED_TYPE_ICONS[type];
  return Icon ? <Icon size={size} color={color} /> : null;
}
